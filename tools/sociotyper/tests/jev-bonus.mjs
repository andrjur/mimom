import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { resolveJevConfig, buildJevRequest, normalizeJevResponse, compareJev, runJevBonus } from '../cloudflare-worker/jev-bonus.js';
import { runCompactPipeline } from '../cloudflare-worker/compact-pipeline.js';

const source = fs.readFileSync(new URL('../cloudflare-worker/worker.js', import.meta.url), 'utf8');
const scope = {};
vm.runInNewContext(source.slice(source.indexOf('const REININ_PROBES ='), source.indexOf('const delay =')) + ';this.definitions = ALL_PROBES;', scope);
const definitions = Array.from(scope.definitions);
const traits = definitions.filter(item => item.kind === 'reinin');
const material = 'Вымышленный технический пример. Я выбрал вариант, проверил последствия и объяснил причину своего поступка.';
const payload = { answers: Object.fromEntries(traits.map(item => [item.id, { type: 'choice', choice: 'a', confidence: 0.85, probabilities: { a: 0.9, b: 0.05, insufficient: 0.05 } }])), usage: { input_tokens: 1000, cost_rub: 0.02 } };
payload.answers.has_examples = { type: 'noul', noul: 0.9 };
const key = 'fixture-polza-not-a-real-key';
assert.equal(resolveJevConfig({}, {}), null);
assert.equal(resolveJevConfig({ POLZA_API_KEY: key }, { jev: { enabled: false } }), null);
assert.equal(resolveJevConfig({ JEV_ENABLED: 'false', POLZA_API_KEY: key }, {}), null);
assert.equal(resolveJevConfig({}, { mode: 'byok', provider: 'dewiar', key }), null, 'never send an unrelated service key');
assert.equal(resolveJevConfig({ JEV_API_KEY: key }, {}).payment, 'site');
assert.equal(resolveJevConfig({ JEV_API_KEY: key }, { jev: { key: 'personal-fixture-key' } }).payment, 'personal');
assert.equal(resolveJevConfig({}, { mode: 'byok', connections: [{ provider: 'polza', key, policy: 'off' }] }), null);
const body = buildJevRequest(material, definitions);
assert.equal(Object.keys(body.questions).length, 16);
assert.equal(body.model, 'typesafe/jev');
assert.equal(body.state.participant_material, material);
assert.equal(body.messages, undefined);
assert.deepEqual(Object.keys(body.questions['reinin-ei'].criteria), ['a', 'b', 'insufficient']);
let normalized = normalizeJevResponse(payload, definitions);
assert.equal(normalized.rows.length, 15);
assert.equal(normalized.costRub, 0.02);
assert.equal(normalized.rows[0].pole, traits[0].poleA);
const noExamples = structuredClone(payload);
noExamples.answers.has_examples.noul = 0.2;
assert.ok(normalizeJevResponse(noExamples, definitions).rows.every(row => row.pole === 'insufficient'));
const ambiguous = structuredClone(payload);
ambiguous.answers[traits[0].id] = { type: 'choice', choice: 'a', confidence: 1, probabilities: { a: 1 / 3, b: 1 / 3, insufficient: 1 / 3 } };
assert.equal(normalizeJevResponse(ambiguous, definitions).rows[0].pole, 'insufficient', 'flat probabilities cannot claim high confidence');
const malformed = structuredClone(payload);
for (const item of traits) malformed.answers[item.id].probabilities.a = 5;
assert.throws(() => normalizeJevResponse(malformed, definitions), /JEV_INVALID_RESPONSE/);
const missing = structuredClone(payload);
delete missing.answers[traits[0].id];
assert.equal(normalizeJevResponse(missing, definitions).rows[0].status, 'invalid');
const main = traits.map((item, index) => ({ probeId: item.id, pole: index === 0 ? item.poleB : item.poleA, confidence: 90, evidence: [{ quoteVerified: true }] }));
let compared = compareJev(normalized, main);
assert.deepEqual(compared.agreement, { agree: 14, disagree: 1, unresolved: 0 });
main[1].evidence = [];
compared = compareJev(normalized, main);
assert.equal(compared.agreement.unresolved, 1, 'unverified main response is not agreement');

let requests = 0;
const fetcher = async (url, options) => {
  requests++;
  assert.equal(url, 'https://polza.ai/api/v1/systemone');
  assert.equal(options.headers.Authorization, `Bearer ${key}`);
  assert.equal(Object.keys(JSON.parse(options.body).questions).length, 16);
  return { ok: true, json: async () => payload };
};
assert.equal((await runJevBonus({ env: {}, material, definitions, fetcher })).status, 'skipped');
assert.equal(requests, 0);
assert.equal((await runJevBonus({ env: { JEV_API_KEY: key }, material, definitions, fetcher })).status, 'done');
assert.equal(requests, 1, 'one request for every Jev question');
assert.equal((await runJevBonus({ env: { JEV_API_KEY: key }, material, definitions, fetcher: async () => ({ ok: false, status: 402 }) })).reason, 'JEV_BALANCE_REQUIRED');
const timeout = await runJevBonus({ env: { JEV_API_KEY: key, JEV_TIMEOUT_MS: 50 }, material, definitions, fetcher: (_url, { signal }) => new Promise((resolve, reject) => signal.addEventListener('abort', () => reject(new Error('aborted')))) });
assert.equal(timeout.reason, 'JEV_TIMEOUT');

const started = [];
let releaseBonus;
const pending = new Promise(resolve => { releaseBonus = resolve; });
const run = bonus => runCompactPipeline({ env: {}, providers: [{ provider: 'dewiar', model: 'fixture' }], text: material, audioContext: '', locks: {}, definitions, diagnostics: {},
  callModel: async (_config, prompt) => {
    started.push('main'); releaseBonus();
    const group = JSON.parse(prompt.match(/ШКАЛЫ: (.+)\n/)[1]);
    return { probes: group.map(item => ({ probeId: item.id, pole: 'insufficient', confidence: 0, evidence: [] })) };
  }, chooseProvider: items => items[0], claimSlot: async () => {}, emit: async () => {}, bonus });
const pipeline = await run(async () => { started.push('bonus'); await pending; return normalized; });
assert.equal(started[0], 'bonus');
assert.ok(started.includes('main'));
assert.equal(pipeline.result.jev.status, 'done');
assert.equal(pipeline.result.tim.abbreviation, '', 'Jev cannot override an insufficient main analysis');
assert.equal(pipeline.result.confidence, 0);
assert.equal(pipeline.requestPlan.maxTextRequests, 5);
assert.equal(pipeline.requestPlan.bonusRequests, 1);
const failed = await run(async () => { throw new Error('fixture unavailable'); });
assert.equal(failed.result.jev.status, 'unavailable');
assert.equal(failed.result.confidence, 0);
console.log('PASS: Jev typed endpoint, 16 questions in one request, no-key skip, key isolation, validation, unknown gate, cost, timeout, parallel start and immutable main result');
