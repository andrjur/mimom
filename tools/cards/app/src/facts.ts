export function getDeckFacts(topic:string,cards:Flashcard[],saved:Record<string,ScienceFact[]>):ScienceFact[]{
 const origin=cards.find(c=>c.topic===topic)?.originTopic||topic;
 if(saved[topic]?.length>=7)return saved[topic];if(saved[origin]?.length>=7)return saved[origin];
 const themed=(lessonFacts as Record<string,ScienceFact[]>)[origin];if(themed?.length>=7)return themed;
 const key=/Физика/.test(origin)?'physics':/Математика/.test(origin)?'math':/Логика/.test(origin)?'logic':/Искусственный интеллект/.test(origin)?'ai':'learning';
 const facts=banks[key].map((short,i)=>({id:key+'-'+i,topic:key==='learning'?'Как учиться':origin,title:short.split(':')[0].split('. ')[0],short,deepDive:[],takeaway:'Попробуйте объяснить этот факт своими словами и придумать пример.',icon:key==='physics'?'🔭':key==='math'?'📐':key==='ai'?'🤖':'💡'}));
 const local=cards.filter(c=>c.topic===topic&&c.id.endsWith('-notes')).slice(0,7).map(c=>({id:'fact-'+c.id,topic,title:c.objective||'Условия применимости',short:c.back.split('\n')[0],deepDive:c.back.split('\n').slice(1).filter(Boolean),takeaway:'Вспомните задачу, в которой это условие важно.',icon:'🔎'}));
 return [...local,...facts];
}
